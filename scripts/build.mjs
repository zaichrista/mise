import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = resolve(root, 'dist');
export const assets = [
  'index.html', 'app-config.js', 'app.js', 'theme.js', 'recipe.js', 'styles.css', 'pwa.js',
  'manifest.webmanifest', 'vendor/lucide.js', 'vendor/LUCIDE-LICENSE',
  'icons/icon.svg', 'icons/icon-192.png', 'icons/icon-512.png',
  'icons/icon-maskable-512.png', 'icons/apple-touch-icon.png'
];
await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });
for (const asset of assets) {
  await mkdir(dirname(resolve(dist, asset)), { recursive: true });
  await cp(resolve(root, asset), resolve(dist, asset));
}
const hash = createHash('sha256');
for (const asset of assets) hash.update(asset).update(await readFile(resolve(dist, asset)));
const worker = await readFile(resolve(root, 'scripts/sw-template.js'), 'utf8');
hash.update(worker);
const version = hash.digest('hex').slice(0, 16);
const generatedWorker = '// Generated by npm run build from scripts/sw-template.js.\n' + worker.replace('__BUILD_VERSION__', version).replace('__PRECACHE_ASSETS__', JSON.stringify(assets));
await writeFile(resolve(root, 'sw.js'), generatedWorker);
await writeFile(resolve(dist, 'sw.js'), generatedWorker);
await writeFile(resolve(dist, '.nojekyll'), '');
console.log(`Built Pot & Page (${version}) in dist/. Ready for GitHub Pages, including repository subpaths.`);
